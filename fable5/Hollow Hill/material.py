"""material.py — the recurring musical material of *Hollow Hill*.

Everything here is written as scale DEGREES so the same figure can be recast
in any mode or key (the ostinato opens Part One in E dorian and returns in
Part Two in E ionian; the Hill theme is minor in Part One, major in Part Two).
"""

import engine as en

# ---------------------------------------------------------------------------
# The Hill ostinato — 13 quavers, grouped 3+3+3+2+2.
# A falling inner voice (8 7 6 ... 2) threaded through a pedal on the fifth.
# ---------------------------------------------------------------------------
OSTINATO = [1, 8, 5, 7, 5, 6, 5, 8, 5, 4, 3, 2, 5]
OST_ACCENTS = (0, 3, 6, 9, 11)
CYCLE = 6.5  # beats per cycle at quaver = half a beat


def ostinato_cycle(sc, ch, t0, base, mode, shift=0, vel=60, accent=12,
                   octave=0, only_accents=False, gate=1.15, jv=4):
    """One 13/8 cycle of the Hill figure starting at t0 (6.5 beats)."""
    for i, deg in enumerate(OSTINATO):
        if only_accents and i not in OST_ACCENTS:
            continue
        v = vel + (accent if i in OST_ACCENTS else 0)
        sc.note(ch, en.pitch(base, mode, deg + shift) + 12 * octave,
                t0 + i * 0.5, 0.5 * gate, v, jt=4, jv=jv)


